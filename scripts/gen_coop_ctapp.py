# 2. params
once("    TileSchedulerArguments scheduler{};\n  };", "    TileSchedulerArguments scheduler{};\n    CtappTp4Params ctapp{};\n  };")
once("    TileSchedulerParams scheduler{};\n    void* workspace{nullptr};", "    TileSchedulerParams scheduler{};\n    CtappTp4Params ctapp{};\n    void* workspace{nullptr};")
once("      scheduler,\n      workspace\n    };", "      scheduler,\n      args.ctapp,\n      workspace\n    };")
