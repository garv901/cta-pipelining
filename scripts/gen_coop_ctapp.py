import re, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = f"{ROOT}/third_party/cutlass/include/cutlass/gemm/kernel/sm90_gemm_tma_warpspecialized_cooperative.hpp"
DST = f"{ROOT}/csrc/sm90_gemm_coop_ctapp.hpp"
s = open(SRC).read()

def once(old, new, flags=0):
    global s
    n = len(re.findall(old, s, flags)) if flags else s.count(old)
    assert n == 1, (n, old[:60])
    s = re.sub(old, new, s, flags=flags) if flags else s.replace(old, new)

